-- Requisitos: qué falta antes de vender, facturar, cobrar online, publicar la tienda y mandar mails.
begin;
create extension if not exists pgtap with schema extensions;
create schema prueba;
grant usage on schema prueba to anon, authenticated;
create function prueba.como_admin() returns void language sql as $$ select set_config('request.jwt.claims', '{"sub":"11111111-1111-1111-1111-111111111111","role":"authenticated"}', true) $$;
create function prueba.como_vendedora() returns void language sql as $$ select set_config('request.jwt.claims', '{"sub":"33333333-3333-3333-3333-333333333333","role":"authenticated"}', true) $$;
create function prueba.hay(p_accion text, p_clave text) returns boolean language sql as $$ select exists (select 1 from jsonb_array_elements(requisitos(p_accion)) x where x ->> 'clave' = p_clave) $$;
grant execute on all functions in schema prueba to anon, authenticated;
select plan(10);
update medios_pago set en_mostrador = false;
update integraciones set mp_access_token = null, mp_webhook_secret = null, smtp_host = null;
update configuracion_fiscal set activa = false;
set local role authenticated; select prueba.como_admin();
select ok(prueba.hay('vender', 'sin_medios'), 'sin medios de pago en el mostrador, no se puede vender');
select ok((select (x ->> 'bloquea')::boolean from jsonb_array_elements(requisitos('vender')) x where x ->> 'clave' = 'sin_medios'), 'y eso frena');
select ok(prueba.hay('facturar', 'arca_apagada'), 'sin ARCA activa, no se factura');
select ok(prueba.hay('cobrar_online', 'mp_sin_token'), 'sin token de Mercado Pago, no se cobra online');
select ok(prueba.hay('cobrar_online', 'mp_sin_secreto'), 'ni sin la clave secreta de los avisos');
select ok(prueba.hay('enviar_mails', 'sin_correo'), 'sin correo conectado, no salen mails');
select throws_ok($$ select requisitos('cualquier_cosa') $$, 'Acción desconocida: cualquier_cosa', 'una acción que no existe da error');
select is((select (x ->> 'puede')::boolean from jsonb_array_elements(requisitos('vender')) x where x ->> 'clave' = 'sin_medios'), true, 'el administrador puede arreglarlo');
select prueba.como_vendedora();
select is((select (x ->> 'puede')::boolean from jsonb_array_elements(requisitos('vender')) x where x ->> 'clave' = 'sin_medios'), false, 'la vendedora ve qué falta pero no puede arreglarlo');
reset role;
update medios_pago set en_mostrador = true;
set local role authenticated; select prueba.como_admin();
select ok(not prueba.hay('vender', 'sin_medios'), 'con medios cargados, el requisito se cumple');
select * from finish();
rollback;
