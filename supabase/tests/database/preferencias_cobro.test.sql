-- Preferencias de cobro: gana lo más específico (dispositivo > persona > rol > general).
begin;
create extension if not exists pgtap with schema extensions;
create schema prueba;
grant usage on schema prueba to anon, authenticated;
create function prueba.como_admin() returns void language sql as $$ select set_config('request.jwt.claims', '{"sub":"11111111-1111-1111-1111-111111111111","role":"authenticated"}', true) $$;
create function prueba.como_vendedora() returns void language sql as $$ select set_config('request.jwt.claims', '{"sub":"33333333-3333-3333-3333-333333333333","role":"authenticated"}', true) $$;
grant execute on all functions in schema prueba to anon, authenticated;
select plan(10);
set local role authenticated; select prueba.como_vendedora();
select throws_ok($$ select registrar_dispositivo('Mi celu') $$, 'Solo el administrador registra dispositivos', 'la vendedora no registra dispositivos');
select throws_ok($$ select guardar_preferencia_cobro('rol', '1', 'qr', false) $$, 'Solo el administrador cambia las preferencias de cobro', 'ni cambia preferencias');
select is(cobro_medios() ->> 'qr', 'true', 'sin preferencias, todo habilitado');
select prueba.como_admin();
select lives_ok($$ select guardar_preferencia_cobro('rol', (select rol_id::text from perfiles where id = '33333333-3333-3333-3333-333333333333'), 'qr', false) $$, 'se apaga el QR para el rol de la vendedora');
select prueba.como_vendedora();
select is(cobro_medios() ->> 'qr', 'false', 'el rol manda si no hay nada más específico');
select is(cobro_medios() ->> 'posnet', 'true', 'y lo demás sigue habilitado');
select prueba.como_admin();
select guardar_preferencia_cobro('usuario', '33333333-3333-3333-3333-333333333333', 'qr', true);
select prueba.como_vendedora();
select is(cobro_medios() ->> 'qr', 'true', 'la persona gana sobre el rol');
select prueba.como_admin();
create temp table dis as select registrar_dispositivo('Celular de Lucía') as clave;
grant all on dis to authenticated;
select guardar_preferencia_cobro('dispositivo', (select id::text from dispositivos where clave = (select clave from dis)), 'qr', false);
select prueba.como_vendedora();
select is(cobro_medios((select clave from dis)) ->> 'qr', 'false', 'el dispositivo gana sobre la persona');
select is(cobro_medios() ->> 'qr', 'true', 'sin ese dispositivo, vale la persona');
select prueba.como_admin();
select guardar_preferencia_cobro('usuario', '33333333-3333-3333-3333-333333333333', 'qr', null);
select prueba.como_vendedora();
select is(cobro_medios() ->> 'qr', 'false', 'quitar la preferencia vuelve a heredar del rol');
select * from finish();
rollback;
